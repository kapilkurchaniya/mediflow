"use server";

import { db, schema } from "@/server/db";
import { getAuthCtx, can } from "@/server/rbac";
import { getAiAction, updateAiActionStatus } from "@/server/ai/actions-service";
import { createPurchaseOrder } from "@/server/domain/purchasing/purchase-orders";
import { createRedistributionTransferDraft } from "@/server/domain/inventory/expiry-redistribution";
import { writeAudit } from "@/server/audit";
import type {
  AddMedicineProposalPayload,
  DraftPoProposalPayload,
  ExpiryRedistributionProposalPayload,
} from "@/server/ai/types";

export interface AiActionResult {
  success: boolean;
  message: string;
  data?: Record<string, unknown>;
  error?: string;
}

/**
 * Executes a pending AI action proposal after explicit user confirmation.
 * Enforces RBAC permissions per intent and logs an audit record upon execution.
 */
export async function confirmAiAction(actionId: string): Promise<AiActionResult> {
  const ctx = await getAuthCtx().catch(() => null);
  if (!ctx || !ctx.tenantId) {
    return { success: false, message: "Unauthorized", error: "Active session required." };
  }

  const action = await getAiAction(actionId, ctx.tenantId);
  if (!action) {
    return { success: false, message: "Not found", error: "The requested action proposal was not found." };
  }

  if (action.status !== "pending_confirmation") {
    return {
      success: false,
      message: "Invalid status",
      error: `Proposal is already in status "${action.status}".`,
    };
  }

  try {
    const rawResult = action.result as { payload?: unknown };
    const payload = rawResult?.payload;

    if (!payload) {
      throw new Error("Missing proposal payload in AI action record.");
    }

    let confirmationResult: Record<string, unknown> = {};
    let successMessage = "Action confirmed successfully.";

    // 1. Intent: add_medicine
    if (action.intent === "add_medicine") {
      if (!can(ctx, "medicine.manage")) {
        return {
          success: false,
          message: "Forbidden",
          error: "Permission 'medicine.manage' required to add medicines.",
        };
      }

      const p = payload as AddMedicineProposalPayload;
      const [newMed] = await db
        .insert(schema.medicines)
        .values({
          tenantId: ctx.tenantId,
          name: p.name,
          genericName: p.genericName || null,
          mrp: p.mrpPaise,
          packSize: p.packSize || "1 Strip",
          isActive: true,
        })
        .returning();

      confirmationResult = { medicineId: newMed.id, medicineName: newMed.name };
      successMessage = `Successfully added "${newMed.name}" to medicine catalogue.`;

      await writeAudit(
        db,
        { tenantId: ctx.tenantId, storeId: ctx.storeId, userId: ctx.userId },
        {
          action: "create",
          entityType: "medicine",
          entityId: newMed.id,
          newValue: { name: newMed.name, mrp: newMed.mrp },
        }
      );
    }

    // 2. Intent: draft_purchase_order
    else if (action.intent === "draft_purchase_order") {
      if (!can(ctx, "purchase.create")) {
        return {
          success: false,
          message: "Forbidden",
          error: "Permission 'purchase.create' required to create purchase orders.",
        };
      }

      const p = payload as DraftPoProposalPayload;
      if (!p.supplierId) {
        throw new Error("Cannot create purchase order without a valid supplier ID.");
      }

      const poResult = await db.transaction(async (tx) => {
        return createPurchaseOrder(tx, ctx, {
          supplierId: p.supplierId,
          expectedDate: new Date(Date.now() + 3 * 86400000).toISOString().split("T")[0],
          notes: "Generated by MediFlow AI Copilot (Autonomous Reorder Chore)",
          items: p.items.map((it) => ({
            medicineId: it.medicineId,
            qty: it.suggestedPacks,
            freeQty: 0,
            rate: it.purchaseRatePaise,
          })),
        });
      });

      confirmationResult = { poId: poResult.id, poNo: poResult.poNo };
      successMessage = `Purchase Order #${poResult.poNo} drafted successfully for ${p.supplierName}.`;

      await writeAudit(
        db,
        { tenantId: ctx.tenantId, storeId: ctx.storeId, userId: ctx.userId },
        {
          action: "create",
          entityType: "purchase_order",
          entityId: poResult.id,
          newValue: { poNo: poResult.poNo, supplierId: p.supplierId },
        }
      );
    }

    // 3. Intent: expiry_redistribution
    else if (action.intent === "expiry_redistribution") {
      if (!can(ctx, "inventory.transfer")) {
        return {
          success: false,
          message: "Forbidden",
          error: "Permission 'inventory.transfer' required to create stock transfers.",
        };
      }

      const p = payload as ExpiryRedistributionProposalPayload;

      const transferResult = await db.transaction(async (tx) => {
        return createRedistributionTransferDraft(tx, {
          tenantId: ctx.tenantId,
          fromStoreId: p.sourceStoreId,
          toStoreId: p.destinationStoreId,
          createdBy: ctx.userId,
          notes: `MediFlow AI Copilot Expiry Redistribution: Transfer from ${p.sourceStoreName} to ${p.destinationStoreName} (Prevented loss: ₹${(p.potentialLossPreventedPaise / 100).toFixed(2)})`,
          items: [
            {
              batchId: p.batchId,
              medicineId: p.medicineId,
              batchNo: p.batchNo,
              expiryDate: p.expiryDate,
              qty: p.transferUnits,
              unitCost: Math.round(p.potentialLossPreventedPaise / Math.max(1, p.transferUnits)),
              mrp: 0,
            },
          ],
        });
      });

      confirmationResult = {
        transferId: transferResult.transferId,
        transferNo: transferResult.transferNo,
      };
      successMessage = `Stock Transfer #${transferResult.transferNo} drafted from ${p.sourceStoreName} to ${p.destinationStoreName}.`;

      await writeAudit(
        db,
        { tenantId: ctx.tenantId, storeId: ctx.storeId, userId: ctx.userId },
        {
          action: "create",
          entityType: "stock_transfer",
          entityId: transferResult.transferId,
          newValue: { transferNo: transferResult.transferNo },
        }
      );
    } else {
      throw new Error(`Unsupported AI proposal intent: ${action.intent}`);
    }

    // Update action status to confirmed
    await updateAiActionStatus(
      actionId,
      ctx.tenantId,
      "confirmed",
      ctx.userId,
      confirmationResult
    );

    return {
      success: true,
      message: successMessage,
      data: confirmationResult,
    };
  } catch (err: unknown) {
    const errorMsg = err instanceof Error ? err.message : String(err);
    await updateAiActionStatus(actionId, ctx.tenantId, "error", ctx.userId, { error: errorMsg });
    return {
      success: false,
      message: "Execution failed",
      error: errorMsg,
    };
  }
}

/**
 * Cancels a pending AI action proposal.
 */
export async function cancelAiAction(actionId: string): Promise<AiActionResult> {
  const ctx = await getAuthCtx().catch(() => null);
  if (!ctx || !ctx.tenantId) {
    return { success: false, message: "Unauthorized", error: "Active session required." };
  }

  const action = await getAiAction(actionId, ctx.tenantId);
  if (!action) {
    return { success: false, message: "Not found", error: "Proposal was not found." };
  }

  if (action.status !== "pending_confirmation") {
    return {
      success: false,
      message: "Invalid status",
      error: `Proposal is in "${action.status}" status and cannot be cancelled.`,
    };
  }

  await updateAiActionStatus(actionId, ctx.tenantId, "cancelled", ctx.userId);

  return {
    success: true,
    message: "Proposal cancelled successfully.",
  };
}
